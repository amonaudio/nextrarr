/**
 * GET /api/tmdb-info/[type]/[id]?lang=it|en
 *
 * Fetches movie/TV metadata from TMDB in the specified language,
 * mapped to the NFO fields used by the NfoEditorTab.
 *
 * Uses append_to_response=credits to get director + writer in one call.
 *
 * In demo mode, returns mock data with IT/EN variations.
 */

import { NextRequest, NextResponse } from 'next/server';
import { loadSettings } from '@/lib/settings-store';
import { fetchSingleMedia, type MediaType } from '@/lib/services/radarr-sonarr';
import { shouldUseMock, getMockSingleMedia } from '@/lib/mock-data';

export const dynamic = 'force-dynamic';

function isValidType(t: string | undefined): t is MediaType {
  return t === 'radarr' || t === 'sonarr';
}

/**
 * Build mock TMDB info for demo mode.
 */
function buildMockTmdbInfo(lang: string, title: string, year: number | string) {
  if (lang === 'it') {
    return {
      title: title,
      originaltitle: title,
      sorttitle: title,
      year: year,
      premiered: `${year}-01-01`,
      runtime: '120',
      mpaa: 'T',
      studio: 'Demo Studio',
      genres: ['Azione', 'Fantascienza'],
      director: 'Regista Demo',
      writer: 'Sceneggiatore Demo',
      plot: `Trama in italiano per ${title}. Questo è un testo demo generato dalla modalità demo di nEXTrarr quando non è configurato un Radarr reale.`,
      outline: `Riassunto italiano per ${title}.`,
      tags: ['demo', 'italiano'],
      uniqueids: [
        { type: 'tmdb', default: true, value: '12345' },
        { type: 'imdb', default: false, value: 'tt0000000' },
      ],
    };
  }
  return {
    title: title,
    originaltitle: title,
    sorttitle: title,
    year: year,
    premiered: `${year}-01-01`,
    runtime: '120',
    mpaa: 'Rated R',
    studio: 'Demo Studio',
    genres: ['Action', 'Science Fiction'],
    director: 'Demo Director',
    writer: 'Demo Writer',
    plot: `English plot for ${title}. This is demo text generated by nEXTrarr's demo mode when no real Radarr is configured.`,
    outline: `English outline for ${title}.`,
    tags: ['demo', 'english'],
    uniqueids: [
      { type: 'tmdb', default: true, value: '12345' },
      { type: 'imdb', default: false, value: 'tt0000000' },
    ],
  };
}

export async function GET(req: NextRequest, { params }: { params: Promise<{ type: string; id: string }> }) {
  const { type, id } = await params;
  if (!isValidType(type)) {
    return NextResponse.json({ status: 'error', message: 'Tipo non valido' }, { status: 400 });
  }
  const mediaId = parseInt(id, 10);
  if (!Number.isFinite(mediaId)) {
    return NextResponse.json({ status: 'error', message: 'ID non valido' }, { status: 400 });
  }

  const lang = req.nextUrl.searchParams.get('lang') ?? 'en';
  const settings = await loadSettings();

  // Demo mode
  if (shouldUseMock(type, settings)) {
    const mockMedia = getMockSingleMedia(type, mediaId);
    if (!mockMedia) {
      return NextResponse.json({ status: 'error', message: 'Media non trovato (demo)' }, { status: 404 });
    }
    return NextResponse.json({
      status: 'success',
      ...buildMockTmdbInfo(lang, mockMedia.title, mockMedia.year ?? 'N/A'),
      demo: true,
    });
  }

  // Real mode
  if (!settings.tmdbApiKey) {
    return NextResponse.json({ status: 'error', message: 'TMDB API Key mancante. Configurala in ⚙️ Impostazioni.' }, { status: 400 });
  }

  let media;
  try {
    media = await fetchSingleMedia(settings, type, mediaId);
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return NextResponse.json({ status: 'error', message: msg }, { status: 500 });
  }

  // Resolve TMDB ID (may need to look up via TVDB for Sonarr)
  let tmdbId = media.tmdbId;
  if (!tmdbId && type === 'sonarr') {
    // Use TMDB find API via TVDB ID
    const tvdbId = media.tvdbId;
    if (tvdbId && settings.tmdbApiKey) {
      try {
        const findRes = await fetch(
          `https://api.themoviedb.org/3/find/${tvdbId}?api_key=${settings.tmdbApiKey}&external_source=tvdb_id`
        );
        if (findRes.ok) {
          const findData = await findRes.json();
          tmdbId = findData.tv_results?.[0]?.id ?? null;
        }
      } catch { /* ignore */ }
    }
  }

  if (!tmdbId) {
    return NextResponse.json({ status: 'error', message: 'TMDB ID non disponibile per questo media.' }, { status: 400 });
  }

  // Fetch movie/TV info + credits in one call
  const endpoint = type === 'radarr' ? 'movie' : 'tv';
  const tmdbLang = lang === 'it' ? 'it-IT' : 'en-US';
  const url = `https://api.themoviedb.org/3/${endpoint}/${tmdbId}?api_key=${settings.tmdbApiKey}&language=${tmdbLang}&append_to_response=credits`;

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 15000);
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' }, signal: controller.signal });
    if (!res.ok) {
      if (res.status === 401 || res.status === 403) {
        return NextResponse.json({ status: 'error', message: 'TMDB API key non valida.' }, { status: 400 });
      }
      if (res.status === 404) {
        return NextResponse.json({ status: 'error', message: `TMDB non ha info per ID ${tmdbId}.` }, { status: 404 });
      }
      return NextResponse.json({ status: 'error', message: `TMDB HTTP ${res.status}` }, { status: 500 });
    }
    const data = await res.json();

    // Map TMDB response → NFO fields
    const title = type === 'radarr' ? data.title : data.name;
    const originalTitle = type === 'radarr' ? data.original_title : data.original_name;
    const releaseDate = type === 'radarr' ? data.release_date : data.first_air_date;
    const year = releaseDate ? releaseDate.slice(0, 4) : '';
    const runtime = type === 'radarr'
      ? (data.runtime ? String(data.runtime) : '')
      : (Array.isArray(data.episode_run_time) && data.episode_run_time.length > 0 ? String(data.episode_run_time[0]) : '');

    // Director + Writer from credits
    const crew = data.credits?.crew ?? [];
    const director = crew.find((c: { job: string }) => c.job === 'Director')?.name ?? '';
    const writers = crew.filter((c: { job: string }) => c.job === 'Writer' || c.job === 'Screenplay').map((c: { name: string }) => c.name);
    const writer = writers.length > 0 ? writers.join(', ') : '';

    // Studio/network
    const studio = type === 'radarr'
      ? (Array.isArray(data.production_companies) && data.production_companies.length > 0 ? data.production_companies[0].name : '')
      : (Array.isArray(data.networks) && data.networks.length > 0 ? data.networks[0].name : '');

    // Genres
    const genres = Array.isArray(data.genres) ? data.genres.map((g: { name: string }) => g.name) : [];

    // Unique IDs
    const uniqueids: { type: string; default: boolean; value: string }[] = [
      { type: 'tmdb', default: true, value: String(tmdbId) },
    ];
    if (data.imdb_id) {
      uniqueids.push({ type: 'imdb', default: false, value: data.imdb_id });
    }
    if (type === 'sonarr' && media.tvdbId) {
      uniqueids.push({ type: 'tvdb', default: false, value: String(media.tvdbId) });
    }

    // MPAA
    const mpaa = type === 'radarr'
      ? (data.release_dates?.results?.find((r: { iso_3166_1: string }) => r.iso_3166_1 === 'US')?.release_dates?.[0]?.certification ?? '')
      : (data.content_rating ?? '');

    return NextResponse.json({
      status: 'success',
      title: title || '',
      originaltitle: originalTitle || '',
      sorttitle: (title || originalTitle || '').toLowerCase(),
      year,
      premiered: releaseDate || '',
      runtime,
      mpaa: mpaa || '',
      studio: studio || '',
      genres,
      director,
      writer,
      plot: data.overview || '',
      outline: (data.overview || '').slice(0, 150),
      tags: [],
      uniqueids,
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return NextResponse.json({ status: 'error', message: `Errore TMDB: ${msg}` }, { status: 500 });
  } finally {
    clearTimeout(timeoutId);
  }
}
